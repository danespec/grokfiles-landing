import fs from 'node:fs';
import assert from 'node:assert/strict';
const source = fs.readFileSync(new URL('../_worker.js', import.meta.url), 'utf8');
const begin = source.indexOf('async function proxyApiWithNormalizedErrors(request, env) {');
const end = source.indexOf('\nasync function handlePublicSearch(', begin);
assert.ok(begin >= 0 && end > begin, 'normalized API proxy function present');
const fn = new Function('proxyProofLayer', `${source.slice(begin,end)}; return proxyApiWithNormalizedErrors;`);
const req = new Request('https://grokarchivehub.com/api/unknown',{method:'GET'});
const html = () => new Response('<html>backend route not found</html>',{status:404,headers:{'Content-Type':'text/html'}});
const json = () => new Response('{"ok":false,"error":"special_404"}',{status:404,headers:{'Content-Type':'application/json'}});
const ok = () => new Response('{"ok":true}',{status:200,headers:{'Content-Type':'application/json'}});
let proxied=0;
const proxy = fn(async (request,env)=>{proxied++; assert.equal(env.marker,true); return html();});
const miss=await proxy(req,{marker:true});
assert.equal(miss.status,404);
assert.match(miss.headers.get('Content-Type'),/application\/json/);
assert.equal(miss.headers.get('Cache-Control'),'no-store');
assert.deepEqual(await miss.json(),{ok:false,error:'not_found'});
assert.equal(proxied,1);
const head = await proxy(new Request(req.url,{method:'HEAD'}),{marker:true});
assert.equal(await head.text(),'');
assert.equal(head.status,404);
const preserveJson = json();
assert.equal(await fn(async()=>preserveJson)(req,{}),preserveJson,'valid upstream JSON errors unchanged');
const preserveOk = ok();
assert.equal(await fn(async()=>preserveOk)(req,{}),preserveOk,'successful upstream JSON unchanged');
assert.match(source,/if \(path\.startsWith\("\/api\/"\)\) \{[\s\S]{0,330}return proxyApiWithNormalizedErrors\(request, env\);/);
