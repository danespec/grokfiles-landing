import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";

const code=fs.readFileSync(new URL("../_worker.js",import.meta.url),"utf8");
const start=code.indexOf("function repairIncomingVisualGalleryInitializer045(html)");
const end=code.indexOf("// GAH-BARAK-LEDGER-036:",start);
assert.ok(start>0&&end>start,"source function found");
const repair=vm.runInNewContext(code.slice(start,end)+"\nrepairIncomingVisualGalleryInitializer045");
const inline='let SUMMARY=null;const SLUG="incoming-visual";function card(x){return `<img loading="lazy" src="${esc(x.thumb_url)}">`;}';
const legacy='<script type="0123456789abcdef01234567-text/javascript">'+inline+'</script>';
const actual=repair(legacy);
assert.ok(actual.includes('data-cfasync="false"'),"trusted initializer bypasses Rocket Loader");
assert.ok(actual.includes('type="text/javascript"'),"restored browser executable MIME");
assert.ok(!actual.includes("0123456789abcdef01234567-text/javascript"),"disabled type removed");
assert.ok(actual.includes('alt="Extracted source image for ${esc(x.efta)}"'),"neutral ID-derived alt text");
assert.ok(actual.includes('src="${esc(x.thumb_url)}"'),"original thumbnail URL retained");
assert.equal(repair(actual),actual,"idempotent");
const sourceText=actual.slice(actual.indexOf(">")+1,actual.lastIndexOf("</script>"));
new vm.Script(sourceText);
const other='<script type="1234567890abcdef12345678-text/javascript">alert(1)</script>';
assert.equal(repair(other),other,"unrecognized JavaScript is not revived");
const suspicious='<script type="application/json">'+inline+'</script>';
assert.equal(repair(suspicious),suspicious,"unrecognized MIME is not revived");
assert.ok(code.includes('if (proxiedPath === "/photos")'));
assert.ok(code.includes('body = repairIncomingVisualGalleryInitializer045(body);'));
assert.ok(code.includes('headers.set("X-GAH-Photos-Script-Repair", "045")'));
assert.ok(code.includes('approvedDefault: false'),"ads remain disabled");
console.log("PASS GAH-PHOTOS-045: only recognized incoming-visual initializer revived; neutral thumbnail alt; idempotent and policy intact");
