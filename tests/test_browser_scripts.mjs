import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
const source = await readFile(new URL('../_worker.js', import.meta.url), 'utf8');
const { default: worker, stripCloudflareHelperAssets } = await import('data:text/javascript;base64,' + Buffer.from(source + '\nexport { stripCloudflareHelperAssets };').toString('base64'));
const token = '88839203d5027c5040989186';
const input = '<script type="' + token + '-text/javascript">window.galleryStarted=true;</script><script src="/cdn-cgi/scripts/7d0fa10a/cloudflare-static/rocket-loader.min.js"></script>';
const restored = stripCloudflareHelperAssets(input);
assert.match(restored, /<script data-cfasync="false" type="text\/javascript">/);
assert.ok(!restored.includes('rocket-loader.min.js'));
assert.match(stripCloudflareHelperAssets(input.replaceAll(token, 'a'.repeat(32))), /type="text\/javascript"/);
const context = {};
vm.runInNewContext(restored.match(/<script[^>]*>(.*?)<\/script>/s)[1], { window: context });
assert.equal(context.galleryStarted, true);
const data = '<script type="application/ld+json">{"@type":"Article"}</script>';
assert.equal(stripCloudflareHelperAssets(data), data);
const ordinary = '<script type="text/javascript">window.ok=true;</script>';
assert.equal(stripCloudflareHelperAssets(ordinary), ordinary);
const agent = await worker.fetch(new Request('https://grokarchivehub.com/agent-tools.js'), {}, {waitUntil() {}});
assert.equal(agent.status, 200);
const script = await agent.text();
new vm.Script(script);
vm.runInNewContext(script, { document: {}, navigator: {} });
const registered = [];
vm.runInNewContext(script, { document: { modelContext: { registerTool(tool) { registered.push(tool.name); return Promise.resolve(); } } }, navigator: {}, window: {}, AbortController });
assert.ok(registered.includes('get_visual_evidence_for_efta'));
assert.ok(registered.includes('get_document_evidence_bundle'));
console.log('PASS upstream gallery script restoration, data-script preservation, complete agent script parsing and registration');
