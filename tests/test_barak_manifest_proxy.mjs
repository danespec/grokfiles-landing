import assert from 'node:assert/strict';
import fs from 'node:fs';
const src=fs.readFileSync(new URL('../_worker.js',import.meta.url),'utf8');
const a=src.indexOf('    // REN-BARAK-008:');
const b=src.indexOf('    if (\n      (request.method === "GET" || request.method === "HEAD") &&\n      (V3_STATIC_ASSET_PATHS.has(url.pathname)',a);
assert.ok(a>=0&&b>a,'manifest proxy precedes static asset fallback');
const code=src.slice(a,b);
const upstreamGood=new Response('{"items":[{"id":"sample"}]}',{status:200,headers:{'Content-Type':'application/json','Cache-Control':'public, max-age=300'}});
const mk=(response)=>new Function('proxyProofLayer','return async function(request,env,path){'+code+';return undefined;}')(async()=>response);
const url='https://grokarchivehub.com/assets/barak-archive-emails.json';
const ok=await mk(upstreamGood)(new Request(url),{},'/assets/barak-archive-emails.json');
assert.equal(ok.status,200);
assert.match(ok.headers.get('Content-Type'),/application\/json/);
assert.equal(ok.headers.get('X-GAH-Barak-Manifest-Proxy'),'verified-wiki-json');
assert.deepEqual(await ok.json(),{items:[{id:'sample'}]});
assert.equal(ok.headers.get('Cache-Control'),'public, max-age=60');
assert.equal(await mk(new Response('[]',{headers:{'Content-Type':'application/json'}}))(new Request(url.replace('emails','pdfs')),{},'/assets/barak-archive-pdfs.json').then(r=>r.status),200);
const fail=await mk(new Response('<html>Backend failure</html>',{status:404,headers:{'Content-Type':'text/html'}}))(new Request(url),{},'/assets/barak-archive-emails.json');
assert.equal(fail.status,502);
assert.equal(fail.headers.get('Cache-Control'),'no-store');
assert.deepEqual(await fail.json(),{ok:false,error:'barak_manifest_temporarily_unavailable'});
const unexpected=await mk(new Response('not-json',{status:200,headers:{'Content-Type':'text/plain'}}))(new Request(url),{},'/assets/barak-archive-emails.json');
assert.equal(unexpected.status,502);
const head=await mk(new Response('{"items":[]}',{status:200,headers:{'Content-Type':'application/json'}}))(new Request(url,{method:'HEAD'}),{},'/assets/barak-archive-emails.json');
assert.equal(head.status,200);assert.equal(await head.text(),'');
const other=await mk(new Response('{}',{headers:{'Content-Type':'application/json'}}))(new Request('https://grokarchivehub.com/assets/other.json'),{},'/assets/other.json');
assert.equal(other,undefined);
