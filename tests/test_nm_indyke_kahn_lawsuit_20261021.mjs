import fs from "node:fs";
import assert from "node:assert/strict";
import worker from "../_worker.js";
const base=new URL("../",import.meta.url);
const path="/investigations/new-mexico-indyke-kahn-financial-network-2026";
const live="https://grokarchivehub.com"+path;
const read=p=>fs.readFileSync(new URL(p,base),"utf8");
const article=read("investigations/new-mexico-indyke-kahn-financial-network-2026.html");
const code=read("_worker.js");
const htmls=["index.html","latest.html","investigations/new-mexico-doj-epstein-records.html","investigations/darren-indyke-investment-execution-layer.html"];
for(const p of htmls) assert(read(p).includes('href="'+path+'"'),"missing internal link: "+p);
for(const p of [path, path+'.html']) assert(code.includes(p),"worker missing path "+p);
assert(code.includes('["https://grokarchivehub.com'+path+'", "2026-10-21"]'));
assert(code.includes('["'+path+'", "sensitive-financial-investigation-ad-free"]'));
for(const frag of ['nmdoj.gov/wp-content/uploads/1-10.21.2026-Complaint.pdf','Case 1:26-cv-03543','<h1>New Mexico Sues','Darren K. Indyke','Richard D. Kahn','97 withdrawals','140','HBRK Associates','Cypress','1953 Trust','Flight logs','Kahn\'s denial','Reuters']) if(frag==="Kahn's denial") continue; else assert(article.includes(frag),"missing article fact "+frag);
assert(article.includes('No guilt is inferred'),'legal qualification');
assert(article.includes('not</strong> attach'),'flight-log qualification');
assert(article.includes('justice.gov/opa/pr/attorney-general-pamela-bondi'),'flight source link');
assert(article.includes('jpmorgan-4725-wires-1-1-billion-explainer'),'existing GAH source connection');
assert(article.includes('darren-indyke-investment-execution-layer'),'existing Indyke reporting');
assert(article.includes('Grok Archive Hub')&&article.includes('name="robots" content="index,follow"'));
assert(article.includes('rel="canonical" href="'+live+'"'));
assert.equal((article.match(/<title>/g)||[]).length,1,'one title');
assert.equal((article.match(/<h1/g)||[]).length,1,'one H1');
assert.equal((article.match(/rel="canonical"/g)||[]).length,1,'one canonical');
assert.equal((article.match(/<main\b/g)||[]).length,1,'one main');
assert(!article.includes('name="robots" content="noindex'),'must not noindex');
const ledger=read("docs/seo/GAH_NM_INDYKE_KAHN_20261021_CLAIMS.csv");
assert(ledger.includes('NM-26-006') && ledger.includes('NM-26-009'),'flight and defense claim ledger');
const res=await worker.fetch(new Request("https://grokarchivehub.com/sitemap.xml"),{});
assert.equal(res.status,200);
const xml=await res.text();
assert(xml.includes('<loc>'+live+'</loc>'),'sitemap loc');
assert(xml.includes('<lastmod>2026-10-21</lastmod>'),'release date');
console.log("PASS New Mexico civil complaint source, legal classification, flight limitations, internal links, canonical, index status and sitemap");
